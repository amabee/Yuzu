type Palette = [string, string, string, string, string, string, string, string];
function palette([
  canvas,
  ink,
  paper,
  primary,
  border,
  sidebar,
  sidebarInk,
  muted,
]: Palette): PreviewColors {
  return { canvas, ink, paper, primary, border, sidebar, sidebarInk, muted };
}
function preset(
  name: string,
  light: Palette,
  dark: Palette,
  headingFont: PreviewTheme["headingFont"],
  bodyFont: PreviewTheme["bodyFont"],
  radius = 12,
): PreviewTheme {
  return {
    ...shared,
    name,
    light: palette(light),
    dark: palette(dark),
    headingFont,
    bodyFont,
    radius,
  };
}
