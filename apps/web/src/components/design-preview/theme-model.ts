export function fontFamily(font: PreviewTheme["bodyFont"]) {
  if (font === "System serif") return "Georgia, 'Times New Roman', serif";
  if (font === "System sans") return "system-ui, sans-serif";
  const variable =
    font === "Instrument Sans"
      ? "--preview-ui"
      : font === "Bricolage Grotesque"
        ? "--preview-display"
        : `--preview-${font.toLowerCase().replaceAll(" ", "-")}`;
  const serif = [
    "Lora",
    "Libre Baskerville",
    "DM Serif Display",
    "Roboto Slab",
    "Fraunces",
  ].includes(font);
  return `var(${variable}), ${serif ? "serif" : "sans-serif"}`;
}
export function contrast(a: string, b: string) {
  const luminance = (hex: string) => {
    const rgb = [1, 3, 5].map((at) => {
      const n = parseInt(hex.slice(at, at + 2), 16) / 255;
      return n <= 0.04045 ? n / 12.92 : ((n + 0.055) / 1.055) ** 2.4;
    });
    return rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722;
  };
  const x = luminance(a),
    y = luminance(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
